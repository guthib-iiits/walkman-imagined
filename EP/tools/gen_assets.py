"""Generate ui_assets.c/.h from the Figma renders and the Tiny5 font."""
import sys
from PIL import Image, ImageFont, ImageDraw

fig, ttf, out_src, out_inc = sys.argv[1:5]

def cls(p):
    r, g, b = p[:3]
    lum = (r * 299 + g * 587 + b * 114) / 1000
    if lum < 90:
        return 'K'
    if r > 180 and g < 120 and not (g > 160):
        return 'R'
    if r > 150 and 110 < g < 200 and b < 110:
        return 'R'      # gold has no ink on a B/W/R panel: draw it red
    return None

imgs = {n: Image.open(f'{fig}/{n}.png').convert('RGB') for n in
        ['menu', 'files', 'mix', 'settings', 'wall']}

ICONS = [
    # name,          src,        window (x0,y0,x1,y1)
    ('folder',       'menu',     (7, 41, 29, 63)),
    ('shuffle',      'menu',     (41, 41, 63, 63)),
    ('playlist',     'menu',     (75, 41, 97, 63)),
    ('disc',         'menu',     (7, 97, 29, 119)),
    ('gear',         'menu',     (40, 97, 62, 119)),
    ('cassette',     'menu',     (75, 97, 97, 119)),
    ('st_repeat',    'menu',     (2, 3, 14, 12)),
    ('st_playpause', 'menu',     (15, 3, 24, 12)),
    ('heart',        'files',    (2, 40, 18, 54)),
    ('folder_small', 'files',    (2, 56, 18, 70)),
    ('song_small',   'files',    (2, 116, 18, 130)),
    ('tape_big',     'mix',      (8, 44, 98, 93)),
    ('rec_dot',      'mix',      (24, 155, 78, 200)),
    ('toggle_on',    'settings', (74, 40, 96, 50)),
    ('toggle_off',   'settings', (74, 74, 96, 84)),
]

def crop_icon(src, win):
    im = imgs[src]
    x0, y0, x1, y1 = win
    pts = [(x, y, cls(im.getpixel((x, y)))) for y in range(y0, y1) for x in range(x0, x1)]
    ink = [(x, y, c) for x, y, c in pts if c]
    bx0 = min(p[0] for p in ink); bx1 = max(p[0] for p in ink) + 1
    by0 = min(p[1] for p in ink); by1 = max(p[1] for p in ink) + 1
    w, h = bx1 - bx0, by1 - by0
    k = [[0] * w for _ in range(h)]
    r = [[0] * w for _ in range(h)]
    for x, y, c in ink:
        (k if c == 'K' else r)[y - by0][x - bx0] = 1
    return w, h, k, r

def pack(rows, w):
    out = []
    for row in rows:
        for bx in range(0, w, 8):
            v = 0
            for i in range(8):
                if bx + i < w and row[bx + i]:
                    v |= 0x80 >> i
            out.append(v)
    return out

def carr(vals, per=16):
    lines = []
    for i in range(0, len(vals), per):
        lines.append('  ' + ', '.join('0x%02X' % v for v in vals[i:i + per]) + ',')
    return '\n'.join(lines)

src = []
inc = []
src.append('/* Generated by tools/gen_assets.py from the Figma "EP/Walkman" frames. Do not edit. */')
src.append('#include "ui_assets.h"\n')

# ---- fonts ----------------------------------------------------------------
def make_font(cname, size, top, rows_n):
    f = ImageFont.truetype(ttf, size)
    asc, desc = f.getmetrics()
    H = asc + desc
    maxw = 0
    glyphs = []
    for c in range(32, 127):
        im = Image.new('L', (32, H), 0)
        d = ImageDraw.Draw(im); d.fontmode = '1'
        d.text((0, 0), chr(c), font=f, fill=255)
        bb = im.getbbox()
        if bb:
            maxw = max(maxw, bb[2])
        glyphs.append((im, max(1, round(f.getlength(chr(c))))))
    bpr = (maxw + 7) // 8
    data, adv = [], []
    for im, a in glyphs:
        for y in range(top, top + rows_n):
            v = 0
            for x in range(bpr * 8):
                if y < H and im.getpixel((x, y)) > 127:
                    v |= 1 << (bpr * 8 - 1 - x)
            data += [(v >> (8 * (bpr - 1 - b))) & 0xFF for b in range(bpr)]
        adv.append(a)
    src.append(f'/* Tiny5 (SIL OFL 1.1) rendered at {size} px: {rows_n} rows x {bpr} byte(s), MSB = leftmost */')
    src.append(f'static const uint8_t {cname}_rows[] = {{\n' + carr(data) + '\n};')
    src.append(f'static const uint8_t {cname}_adv[95] = {{\n' + carr(adv) + '\n};')
    src.append(f'const ui_font_t {cname} = {{ {rows_n}, {bpr}, {cname}_rows, {cname}_adv }};\n')

make_font('font_small', 8, 1, 8)
make_font('font_medium', 12, 1, 12)

# ---- wallpaper ------------------------------------------------------------
wall = imgs['wall']
rows = [[1 if (lambda p: p[0] > 200 and p[1] < 150)(wall.getpixel((x, y))) else 0
         for x in range(104)] for y in range(212)]
src.append('/* Wallpaper mask (1 = pink block), 104 x 212 */')
src.append('const uint8_t ui_wallpaper[13 * 212] = {\n' + carr(pack(rows, 104)) + '\n};\n')

# ---- icons ----------------------------------------------------------------
for name, s, win in ICONS:
    w, h, k, r = crop_icon(s, win)
    kb, rb = pack(k, w), pack(r, w)
    has_r = any(rb)
    src.append(f'static const uint8_t {name}_k[] = {{\n{carr(kb)}\n}};')
    if has_r:
        src.append(f'static const uint8_t {name}_r[] = {{\n{carr(rb)}\n}};')
    src.append(f'const ui_icon_t icon_{name} = {{ {w}, {h}, {name}_k, {name + "_r" if has_r else "0"} }};\n')
    inc.append(f'extern const ui_icon_t icon_{name};   /* {w} x {h} */')

open(out_src, 'w').write('\n'.join(src))
open(out_inc, 'w').write('''/* Generated by tools/gen_assets.py from the Figma "EP/Walkman" frames. Do not edit. */
#ifndef UI_ASSETS_H
#define UI_ASSETS_H

#include <stdint.h>

/* Two-plane bitmap: rows packed MSB-first, (w + 7) / 8 bytes per row.
 * A set bit in k draws black, a set bit in r draws red, both clear = transparent. */
typedef struct {
  uint8_t w;
  uint8_t h;
  const uint8_t *k;
  const uint8_t *r;
} ui_icon_t;

/* Fixed-height bitmap font for ASCII 32..126. */
typedef struct {
  uint8_t h;
  uint8_t bytes_per_row;
  const uint8_t *rows;
  const uint8_t *advance;
} ui_font_t;

extern const ui_font_t font_small;    /* Tiny5 8 px  (status bar, 2x for titles) */
extern const ui_font_t font_medium;   /* Tiny5 12 px (lists, track info) */
extern const uint8_t ui_wallpaper[13 * 212];

''' + '\n'.join(inc) + '\n\n#endif /* UI_ASSETS_H */\n')
print('ok')
