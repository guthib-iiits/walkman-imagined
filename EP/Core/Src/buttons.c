/**
  ******************************************************************************
  * @file    buttons.c
  * @brief   Debounced D-pad, centre and power buttons with click / hold / repeat.
  *          Polled from the main loop, so the EXTI lines CubeMX set up on the
  *          D-pad pins are not used.
  ******************************************************************************
  */
#include "buttons.h"
#include "walkman_config.h"

#define BTN_DEBOUNCE_MS  25U       /* a level must hold this long to count */
#define BTN_HOLD_MS      600U      /* pressed this long = "hold" instead of "click" */
#define BTN_REPEAT_MS    150U      /* while held, send REPEAT this often (fast scroll / seek) */

/* Where each button is wired (pins come from main.h, generated by CubeMX). */
typedef struct {
  GPIO_TypeDef *port;
  uint16_t pin;
  bool active_low;                 /* true: pressed = pin reads 0 (switch to GND) */
} btn_pin_t;

static const btn_pin_t pins[BTN_COUNT] = {
  [BTN_UP]     = { BTN_UP_GPIO_Port,     BTN_UP_Pin,     BTN_ACTIVE_LOW },
  [BTN_DOWN]   = { BTN_DOWN_GPIO_Port,   BTN_DOWN_Pin,   BTN_ACTIVE_LOW },
  [BTN_LEFT]   = { BTN_LEFT_GPIO_Port,   BTN_LEFT_Pin,   BTN_ACTIVE_LOW },
  [BTN_RIGHT]  = { BTN_RIGHT_GPIO_Port,  BTN_RIGHT_Pin,  BTN_ACTIVE_LOW },
  [BTN_CENTER] = { BTN_CENTER_GPIO_Port, BTN_CENTER_Pin, BTN_ACTIVE_LOW },
  [BTN_POWER]  = { BTN_POWER_GPIO_Port,  BTN_POWER_Pin,  BTN_POWER_ACTIVE_LOW },
};

/* Per-button state for debouncing and hold detection. */
typedef struct {
  bool raw;                        /* last level read from the pin (may bounce) */
  bool stable;                     /* debounced level: true = pressed */
  bool held;                       /* HOLD already sent for this press */
  uint32_t changed_at;             /* tick when raw last changed */
  uint32_t pressed_at;             /* tick when the debounced press started */
  uint32_t repeat_at;              /* tick for the next REPEAT event */
} btn_state_t;

static btn_state_t st[BTN_COUNT];
static uint32_t last_activity;

void buttons_init(void)
{
  /* PC13 is the WKUP4 pin; CubeMX leaves it unconfigured while running. */
  GPIO_InitTypeDef g = {0};
  __HAL_RCC_GPIOC_CLK_ENABLE();
  g.Pin = BTN_POWER_Pin;
  g.Mode = GPIO_MODE_INPUT;
  g.Pull = BTN_POWER_ACTIVE_LOW ? GPIO_PULLUP : GPIO_PULLDOWN;
  HAL_GPIO_Init(BTN_POWER_GPIO_Port, &g);

  /* The D-pad pins were configured as EXTI inputs; reading IDR still works. */
  for (int i = 0; i < BTN_COUNT; i++)
  {
    st[i].raw = st[i].stable = false;
  }
  last_activity = HAL_GetTick();
}

/* true when button i is physically pressed, whatever the pin polarity. */
static bool read_pin(int i)
{
  GPIO_PinState s = HAL_GPIO_ReadPin(pins[i].port, pins[i].pin);
  return pins[i].active_low ? (s == GPIO_PIN_RESET) : (s == GPIO_PIN_SET);
}

/* Scan all buttons once. Returns true and fills *ev when something happened;
 * call it in a loop until it returns false. Events per press:
 *   short press:  CLICK on release
 *   long press:   HOLD after 600 ms, REPEAT every 150 ms, RELEASE at the end */
bool buttons_poll(btn_event_t *ev)
{
  uint32_t now = HAL_GetTick();

  for (int i = 0; i < BTN_COUNT; i++)
  {
    btn_state_t *b = &st[i];
    bool r = read_pin(i);

    /* Debounce: restart the timer on every change, accept the new level only
     * once it has been steady for BTN_DEBOUNCE_MS. */
    if (r != b->raw)
    {
      b->raw = r;
      b->changed_at = now;
    }
    if (b->raw != b->stable && (now - b->changed_at) >= BTN_DEBOUNCE_MS)
    {
      b->stable = b->raw;
      last_activity = now;
      if (b->stable)               /* just pressed: start timing for HOLD */
      {
        b->pressed_at = now;
        b->held = false;
      }
      else                         /* just released */
      {
        ev->id = (btn_id_t)i;
        ev->type = b->held ? BTN_EV_RELEASE : BTN_EV_CLICK;
        return true;
      }
    }
    if (b->stable)                 /* still down: HOLD once, then REPEAT */
    {
      if (!b->held && (now - b->pressed_at) >= BTN_HOLD_MS)
      {
        b->held = true;
        b->repeat_at = now + BTN_REPEAT_MS;
        ev->id = (btn_id_t)i;
        ev->type = BTN_EV_HOLD;
        return true;
      }
      if (b->held && (int32_t)(now - b->repeat_at) >= 0)
      {
        b->repeat_at = now + BTN_REPEAT_MS;
        ev->id = (btn_id_t)i;
        ev->type = BTN_EV_REPEAT;
        return true;
      }
    }
  }
  return false;
}

bool buttons_any_down(void)
{
  for (int i = 0; i < BTN_COUNT; i++)
  {
    if (st[i].stable)
    {
      return true;
    }
  }
  return false;
}

/* Tick of the last press or release. Used for idle timeouts (audio power-down,
 * standby) and to hold off the slow colour refresh while the user is active. */
uint32_t buttons_last_activity(void)
{
  return last_activity;
}
